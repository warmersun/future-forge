#!/usr/bin/env python3
"""Regenerate js/server/share-glyphs.mjs from Noto Sans (SIL OFL 1.1).

The share preview is drawn by sharp/librsvg inside the Neon Function, which has
no system fonts, so SVG <text> renders as empty boxes there. Instead the label
is drawn as plain SVG paths baked from this font. No font lookup at runtime.

    python3 scripts/build-share-glyphs.py path/to/NotoSans-VariableFont_wdth,wght.ttf

Needs fontTools (pip install fonttools). Output is committed; run this only to
change the font, weight or character set.
"""
import json
import sys
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "js" / "server" / "share-glyphs.mjs"
WEIGHT = 700

# Printable ASCII plus the punctuation card text uses.
EXTRA = "\u00b7\u2014\u2013\u2018\u2019\u201c\u201d\u2026\u00b0\u00d7\u2022\u00a0"
CHARS = "".join(chr(c) for c in range(0x20, 0x7F)) + EXTRA


def main(src):
    font = TTFont(src)
    if "fvar" in font:
        axes = {a.axisTag for a in font["fvar"].axes}
        loc = {"wght": WEIGHT}
        if "wdth" in axes:
            loc["wdth"] = 100
        font = instancer.instantiateVariableFont(font, loc)
    cmap = font.getBestCmap()
    gs = font.getGlyphSet()
    upem = font["head"].unitsPerEm
    name = font["name"]
    copyright_ = name.getDebugName(0) or ""
    family = name.getDebugName(1) or ""
    glyphs = {}
    for ch in CHARS:
        gname = cmap.get(ord(ch))
        if gname is None:
            raise SystemExit(f"font has no glyph for U+{ord(ch):04X}")
        pen = SVGPathPen(gs, ntos=lambda v: str(round(v)))
        gs[gname].draw(TransformPen(pen, (1, 0, 0, -1, 0, 0)))
        glyphs[ch] = [round(gs[gname].width), pen.getCommands()]
    body = json.dumps(glyphs, ensure_ascii=True, separators=(",", ":"))
    OUT.write_text(
        "// Generated by scripts/build-share-glyphs.py. Do not edit by hand.\n"
        f"// Glyph outlines from {family} Bold (wght {WEIGHT}).\n"
        f"// {copyright_}\n"
        "// Licensed under the SIL Open Font License 1.1; see js/server/fonts/OFL.txt.\n"
        "// Paths are in font units with y pointing down; the baseline is y = 0.\n"
        f"export const UNITS_PER_EM = {upem};\n"
        f"/** @type {{Record<string, [number, string]>}} */\n"
        f"export const GLYPHS = {body};\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(glyphs)} glyphs, {OUT.stat().st_size} bytes")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
